"""Generate the full OpenAPI contract from actual application routes.

python -m backend.scripts.export_contract [--check]
Requires the lightweight OCR API dependencies to include mounted OCR routes.
"""
import argparse
import copy
import json
from pathlib import Path
import tempfile
import yaml
from fastapi.routing import APIRoute
from backend.core.config import Settings
from backend.main import create_app

ROOT = Path(__file__).resolve().parents[3]
DESTINATION = ROOT / "docs" / "api-contract.yaml"


def permission(dependant):
    names = {getattr(dependant.call, "__name__", "")}
    for child in dependant.dependencies:
        names.update(permission(child))
    return names


def generate():
    with tempfile.TemporaryDirectory(prefix="pdf-schema-") as directory:
        root = Path(directory)
        app = create_app(Settings(_env_file=None, database_url=f"sqlite:///{root}/contract.db",
            storage_dir=root/"files", ocr_storage=root/"files", jwt_secret="schema-generation-only-0123456789abcdef",
            ocr_enabled=True))
        if not app.state.ocr_mounted:
            raise RuntimeError("Install pdf_ocr_module/ocr_service/requirements.txt before generating the full contract")
        schema = copy.deepcopy(app.openapi())
        schema["info"]["description"] = "从实际FastAPI路由生成；路径已含/api/v1，不重复添加前缀。权限扩展来自服务端依赖，分享链接凭token访问。"
        for route in app.routes:
            if not isinstance(route, APIRoute) or not route.include_in_schema:
                continue
            names = permission(route.dependant)
            access = "admin" if "require_admin" in names else "editor" if "require_editor" in names else "user" if "current_user" in names else "public"
            for method in route.methods:
                operation = schema["paths"].get(route.path, {}).get(method.lower())
                if operation is not None:
                    operation["x-permission"] = access
        # IDs/order remain deterministic across platforms and engine config.
        app.state.engine.dispose()
        if getattr(app.state,"ocr_engine",None) is not None:
            app.state.ocr_engine.dispose()
        return schema


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = generate()
    if args.check:
        actual = yaml.safe_load(DESTINATION.read_text(encoding="utf-8"))
        if actual != schema:
            raise SystemExit("OpenAPI contract differs from the application; regenerate docs/api-contract.yaml")
    else:
        DESTINATION.write_text("# Generated by python -m backend.scripts.export_contract; do not hand-edit.\n" +
            yaml.safe_dump(schema, allow_unicode=True, sort_keys=False),encoding="utf-8")
    methods=sum(len([m for m in value if m in {"get","post","patch","put","delete","head","options"}]) for value in schema["paths"].values())
    print(f"Contract checked: {len(schema['paths'])} paths, {methods} operations")


if __name__ == "__main__":
    main()
